-- 增量初始化：保留原 demo 表和记录，不执行 DROP 或清空数据。
CREATE TABLE IF NOT EXISTS `user` (
 user_id BIGINT PRIMARY KEY AUTO_INCREMENT, user_name VARCHAR(30) NOT NULL,
 nick_name VARCHAR(30) NOT NULL, email VARCHAR(50) DEFAULT '', phonenumber VARCHAR(11) DEFAULT '',
 avatar VARCHAR(100) DEFAULT '', password VARCHAR(255) NOT NULL, status CHAR(1) DEFAULT '0',
 del_flag CHAR(1) DEFAULT '0', login_ip VARCHAR(128) DEFAULT '', login_date DATETIME NULL,
 create_by VARCHAR(64) DEFAULT '', create_time DATETIME NULL, update_by VARCHAR(64) DEFAULT '', update_time DATETIME NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS role (
 role_id BIGINT PRIMARY KEY AUTO_INCREMENT, role_name VARCHAR(30) NOT NULL,
 role_tag VARCHAR(30), role_sort INT NOT NULL DEFAULT 1, status CHAR(1) NOT NULL DEFAULT '0',
 del_flag CHAR(1) DEFAULT '0', create_by VARCHAR(64) DEFAULT '', create_time DATETIME NULL,
 update_by VARCHAR(64) DEFAULT '', update_time DATETIME NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS user_role (user_id BIGINT NOT NULL, role_id BIGINT NOT NULL, PRIMARY KEY(user_id,role_id)) ENGINE=InnoDB;
UPDATE `user` SET password='' WHERE password IS NULL;
ALTER TABLE `user` MODIFY password VARCHAR(255) NOT NULL;

CREATE TABLE IF NOT EXISTS rental_house (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, code VARCHAR(32) NOT NULL UNIQUE, title VARCHAR(80) NOT NULL,
 address VARCHAR(200) NOT NULL, area DECIMAL(8,2) NOT NULL, monthly_rent DECIMAL(12,2) NOT NULL,
 deposit DECIMAL(12,2) NOT NULL DEFAULT 0, status VARCHAR(16) NOT NULL DEFAULT 'VACANT',
 version INT NOT NULL DEFAULT 0, deleted TINYINT NOT NULL DEFAULT 0,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP, updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 INDEX idx_house_status (deleted,status)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS rental_tenant (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, name VARCHAR(40) NOT NULL, phone VARCHAR(11) NOT NULL UNIQUE,
 email VARCHAR(100) DEFAULT '', remark VARCHAR(200) DEFAULT '', deleted TINYINT NOT NULL DEFAULT 0,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS rental_contract (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, contract_no VARCHAR(40) NOT NULL UNIQUE,
 house_id BIGINT NOT NULL, tenant_id BIGINT NOT NULL, start_date DATE NOT NULL, end_date DATE NOT NULL,
 months INT NOT NULL, monthly_rent DECIMAL(12,2) NOT NULL, deposit DECIMAL(12,2) NOT NULL,
 status VARCHAR(16) NOT NULL DEFAULT 'ACTIVE', closed_at DATETIME NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 -- 唯一生成列为行锁之外提供数据库级的重复出租兜底。
 active_house_id BIGINT GENERATED ALWAYS AS (CASE WHEN status='ACTIVE' THEN house_id ELSE NULL END) STORED,
 UNIQUE KEY uk_active_house (active_house_id), INDEX idx_contract_tenant (tenant_id,status),
 FOREIGN KEY (house_id) REFERENCES rental_house(id), FOREIGN KEY (tenant_id) REFERENCES rental_tenant(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS rental_bill (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, contract_id BIGINT NOT NULL, period CHAR(7) NOT NULL,
 due_date DATE NOT NULL, amount DECIMAL(12,2) NOT NULL, paid_amount DECIMAL(12,2) NOT NULL DEFAULT 0,
 status VARCHAR(16) NOT NULL DEFAULT 'UNPAID', UNIQUE KEY uk_contract_period(contract_id,period),
 INDEX idx_bill_due (status,due_date), FOREIGN KEY (contract_id) REFERENCES rental_contract(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS rental_payment (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, bill_id BIGINT NOT NULL, amount DECIMAL(12,2) NOT NULL,
 request_id VARCHAR(64) NOT NULL UNIQUE, method VARCHAR(16) NOT NULL,
 note VARCHAR(200) DEFAULT '', actor VARCHAR(30) NOT NULL, created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 INDEX idx_payment_time(created_at), FOREIGN KEY (bill_id) REFERENCES rental_bill(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS rental_audit (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, actor VARCHAR(30) NOT NULL, action VARCHAR(60) NOT NULL,
 target VARCHAR(120) NOT NULL, request_id VARCHAR(64) NOT NULL, created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 INDEX idx_audit_time(created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
